// Kiểm tra đầu vào từ mọi nguồn. Không dùng Number(value) || 0 vì sẽ biến ô trống thành 0.
function isValidScoreInput(value) {
    return value !== null && value !== undefined &&
        typeof value !== 'boolean' && String(value).trim() !== '' &&
        Number.isFinite(Number(value)) && Number(value) >= 0 && Number(value) <= 10;
}

// Xác thực toàn bộ file trước khi ghi dữ liệu, kể cả từng cột điểm thành phần.
function validateImportedGrades(grades) {
    const errors = [];
    grades.forEach((item, index) => {
        const line = index + 2; // Excel thường có tiêu đề ở hàng 1
        const code = String(item?.code ?? '').trim();
        const label = `Dòng ${line}${code ? ` (${code})` : ''}`;
        if (!code) errors.push(`${label}: thiếu mã môn`);
        if (!isValidScoreInput(item?.score)) errors.push(`${label}: điểm tổng kết phải từ 0 đến 10`);
        if (Array.isArray(item?.scoresList)) {
            item.scoresList.forEach((entry, j) => {
                if (!isValidScoreInput(entry?.score)) errors.push(`${label}, cột điểm ${j + 1}: điểm phải từ 0 đến 10`);
            });
        }
    });
    return errors;
}

// Điểm tổng kết được HIỂN THỊ và LƯU với 1 chữ số thập phân.
// So sánh trên cùng độ chính xác để không có trường hợp hiển thị 5.0 nhưng lại báo CĐ.
function roundFinalScore(score) {
    return Math.round((Number(score) + Number.EPSILON) * 10) / 10;
}
function hasCourseScore(g) {
    return !!g && g.score !== null && g.score !== undefined && String(g.score).trim() !== ''
        && isValidScoreInput(g.score);
}
// Với môn đã có điểm: điểm số là nguồn xác định Đ/CĐ, không tin chuỗi trạng thái cũ.
function isPassedCourse(g) {
    return hasCourseScore(g) && roundFinalScore(g.score) >= 5.0;
}
function isFailedCourse(g) {
    return hasCourseScore(g) && roundFinalScore(g.score) < 5.0;
}
function getCourseStatus(g) {
    if (!hasCourseScore(g)) return String(g?.status || 'Chưa học');
    return isPassedCourse(g) ? 'Đ' : 'CĐ';
}
// Chuẩn hóa trạng thái của dữ liệu cũ đã từng bị lỗi làm tròn.
function normalizeGradeStatuses(grades) {
    let changed = false;
    (grades || []).forEach(g => {
        if (!g || !hasCourseScore(g)) return;
        const rounded = roundFinalScore(g.score);
        if (Number(g.score) !== rounded || typeof g.score !== 'number') {
            g.score = rounded;
            changed = true;
        }
        const expected = getCourseStatus(g);
        if (g.status !== expected) { g.status = expected; changed = true; }
    });
    return changed;
}
// Đếm mỗi mã môn một lần (bản ghi cuối cùng thay thế lần học cũ).
function getLatestCourses(grades) {
    const byCode = new Map();
    (grades || []).forEach((g, i) => {
        if (!g || !g.code) return;
        const code = String(g.code).trim().toUpperCase();
        if (byCode.has(code)) byCode.delete(code);
        byCode.set(code, {...g, code, status: getCourseStatus(g)});
    });
    return [...byCode.values()];
}
function convertScoreTo4(score) {
    const x = Number(score);
    if (x >= 9) return 4;
    if (x >= 8) return 3.5;
    if (x >= 7) return 3;
    if (x >= 6) return 2.5;
    if (x >= 5) return 2;
    if (x >= 4) return 1.5;
    if (x >= 3) return 1;
    return 0;
}
function getCourseMetrics(grades) {
    const courses = getLatestCourses(grades).filter(g => !isExcludedCourse(g));
    const passed = courses.filter(isPassedCourse);
    const attempted = courses.filter(g => hasCourseScore(g) && (isPassedCourse(g) || isFailedCourse(g)));
    const earnedCredits = passed.reduce((sum,g) => sum + getStandardCredit(g.code,g.tc), 0);
    const passedWeighted = passed.reduce((sum,g) => sum + getStandardCredit(g.code,g.tc) * Number(g.score), 0);
    const attemptedCredits = attempted.reduce((sum,g) => sum + getStandardCredit(g.code,g.tc), 0);
    const attemptedWeighted = attempted.reduce((sum,g) => sum + getStandardCredit(g.code,g.tc) * Number(g.score), 0);
    const attemptedWeighted4 = attempted.reduce((sum,g) => sum + getStandardCredit(g.code,g.tc) * convertScoreTo4(g.score), 0);
    const passedWeighted4 = passed.reduce((sum,g) => sum + getStandardCredit(g.code,g.tc) * convertScoreTo4(g.score), 0);
    return {
        earnedCredits, passedCredits: earnedCredits, passedWeighted, passedWeighted4,
        attemptedCredits, attemptedWeighted, attemptedWeighted4,
        // GPA ở Bảng điểm và GPA học kỳ: tất cả học phần có điểm, kể cả môn rớt.
        gpa10: attemptedCredits ? attemptedWeighted / attemptedCredits : 0,
        gpa4: attemptedCredits ? attemptedWeighted4 / attemptedCredits : 0,
        // GPA tích lũy ở Dashboard/Mục tiêu: chỉ học phần đạt (>= 5.0).
        passedGPA10: earnedCredits ? passedWeighted / earnedCredits : 0,
        passedGPA4: earnedCredits ? passedWeighted4 / earnedCredits : 0
    };
}
