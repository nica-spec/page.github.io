// Dùng mã môn chuẩn hóa làm khóa duy nhất: bản ghi mới nhất thay thế bản cũ.
function mergeGradesReplacingOld(oldGrades, incomingGrades) {
    const map = new Map();
    for (const g of [...(oldGrades || []), ...(incomingGrades || [])]) {
        if (!g || typeof g !== 'object') continue;
        const code = String(g.code || '').trim().toUpperCase();
        if (!code) continue;
        const clean = { ...g, code, score: hasCourseScore(g) ? roundFinalScore(g.score) : g.score, status: getCourseStatus(g) };
        if (map.has(code)) map.delete(code);
        map.set(code, clean);
    }
    return [...map.values()];
}
function downloadGradesJSON(grades, studentId) {
    const blob = new Blob([JSON.stringify(grades, null, 2)], { type: 'application/json;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = `Bang_Diem_${studentId}.json`;
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
}

