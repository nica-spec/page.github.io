        if (/^(?:học\s*k[ỳìi]\s*)?hè$/i.test(text) || /^summer$/i.test(text)) return '3';
        const matched = text.match(/(?:hk|học\s*k[ỳìi]|semester|k[ỳìi])?\s*([123])(?:\D|$)/i);
